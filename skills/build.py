#!/usr/bin/env python3
"""Generate the per-harness skill files from skills/_source/body.md.

Edit the shared body (or a harness entry below), run `python3 skills/build.py`, commit the result.
`python3 skills/build.py --check` exits non-zero if any generated file is out of date (used by the tests).
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "_source"
BODY = (SRC / "body.md").read_text(encoding="utf-8")

DESCRIPTION = (
    "Work with ServiceNow through the servicenow MCP server - look up and search incidents/changes/problems, "
    "triage the unassigned queue, assign incidents to approved teams, create/update/resolve incidents, manage "
    "problems (root cause, workaround, known errors, linking incidents), approve changes pending for the "
    "integration account, and review/edit the on-call roster. Writes always preview first and need explicit "
    "user approval."
)

HERMES_FRONT = f"""---
name: servicenow
description: {DESCRIPTION}
version: 2.0.0
author: local
required_environment_variables:
  - name: SERVICENOW_MCP_TOKEN
    prompt: Bearer token for the ServiceNow MCP server
    help: Generated by the server's setup script and shown once; stored only in ~/.hermes/.env
    required_for: authenticating to the MCP endpoint
metadata:
  hermes:
    tags: [servicenow, itsm, incidents, problem-management, change-management, on-call, triage, mcp]
    category: devops
---
"""
SIMPLE_FRONT = f"---\nname: servicenow\ndescription: {DESCRIPTION}\n---\n"
PAPERCLIP_FRONT = f"---\nname: servicenow\nslug: servicenow\ndescription: {DESCRIPTION}\n---\n"

CHATGPT_HEAD = """# ServiceNow assistant instructions

Paste these into the instructions of a ChatGPT Project or custom GPT that has the ServiceNow MCP server
connected (see SETUP.md in this folder for what is and is not possible with ChatGPT).

"""

NAMING = {
    "hermes": "Its tools appear as `mcp_servicenow_<tool>`.",
    "claude-desktop": "Its tools come from the `servicenow` connector; call them by the names listed below.",
    "openclaw": "Its tools may be shown with a server prefix (for example `servicenow__search_incidents`); "
                "call them by the names the tool list shows.",
    "paperclip": "Depending on the agent runtime the tool names carry a prefix (for example "
                 "`mcp__servicenow__search_incidents` in Claude Code or `mcp_servicenow_search_incidents` in "
                 "Hermes); call them by the names the tool list shows.",
    "chatgpt-desktop": "Call its tools by the names listed below.",
    "generic": "Depending on the client, tool names may carry a prefix for the server (for example "
               "`servicenow__search_incidents` or `mcp__servicenow__search_incidents`); call them by the names "
               "the tool list shows.",
}

SETUP_NOTE = (
    "\n\n## Setup\n\nInstall and connection steps for this client are in `SETUP.md` next to this file "
    "(the MCP server URL and token are configured in the client, never in this skill).\n"
)

APPROVAL_NOTE = (
    "\n\nKeep the client's own tool-approval prompt enabled for write tools; a human must approve every write call.\n"
)


def render(kind: str) -> str:
    body = BODY.replace("{{NAMING}}", NAMING[kind]).rstrip("\n") + "\n"
    if kind == "hermes":
        conn = (SRC / "hermes-connection.md").read_text(encoding="utf-8")
        head, _, tail = body.partition("\n## Failures")
        return HERMES_FRONT + "\n" + head.rstrip("\n") + "\n\n" + conn + "\n## Failures" + tail
    front = {"claude-desktop": SIMPLE_FRONT, "openclaw": SIMPLE_FRONT, "paperclip": PAPERCLIP_FRONT,
             "generic": SIMPLE_FRONT}.get(kind)
    if front is None:  # chatgpt
        return CHATGPT_HEAD + body.rstrip("\n") + APPROVAL_NOTE
    head, _, tail = body.partition("\n## Failures")
    return (front + "\n" + head.rstrip("\n") + "\n\n## Failures" + tail.rstrip("\n") + "\n"
            + APPROVAL_NOTE.rstrip("\n") + SETUP_NOTE)


OUTPUTS = {
    "generic": "generic/servicenow/SKILL.md",
    "hermes": "hermes/servicenow/SKILL.md",
    "claude-desktop": "claude-desktop/servicenow/SKILL.md",
    "openclaw": "openclaw/servicenow/SKILL.md",
    "paperclip": "paperclip/servicenow/SKILL.md",
    "chatgpt-desktop": "chatgpt-desktop/instructions.md",
}


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for kind, rel in OUTPUTS.items():
        path = ROOT / rel
        text = render(kind)
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            print("wrote", rel)
    if stale:
        print("out of date (run: python3 skills/build.py):", *stale, sep="\n  ")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
